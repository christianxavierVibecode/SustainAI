-- SustainAI PostgreSQL schema
-- PostgreSQL 15+
-- Notes:
-- 1. UUIDs are generated with gen_random_uuid() (built-in on supported PostgreSQL versions).
-- 2. Store only server-side Gemini credentials; never store API keys in these tables.
-- 3. analysis_records.result stores the validated Gemini JSON response as JSONB.
-- 4. Waste-bank prices are reference/demo data and should include a validity timestamp.

CREATE TABLE users (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username        VARCHAR(50) NOT NULL UNIQUE,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   TEXT NOT NULL,
    full_name       VARCHAR(120),
    avatar_url      TEXT,
    email_verified  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE waste_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE waste_sub_categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT NOT NULL REFERENCES waste_categories(id) ON DELETE RESTRICT,
    name         VARCHAR(150) NOT NULL,
    description  TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_waste_sub_category UNIQUE (category_id, name)
);

CREATE TABLE waste_banks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(180) NOT NULL,
    address         TEXT NOT NULL,
    city            VARCHAR(100),
    province        VARCHAR(100),
    postal_code     VARCHAR(15),
    latitude        NUMERIC(10, 7),
    longitude       NUMERIC(10, 7),
    phone           VARCHAR(30),
    website_url     TEXT,
    opening_hours   JSONB,
    description     TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_waste_bank_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_waste_bank_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- A bank can accept many sub-categories; a sub-category can be accepted by many banks.
-- price_per_kg is in Indonesian Rupiah (IDR) per kilogram unless unit says otherwise.
CREATE TABLE waste_bank_prices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waste_bank_id       BIGINT NOT NULL REFERENCES waste_banks(id) ON DELETE CASCADE,
    sub_category_id     BIGINT NOT NULL REFERENCES waste_sub_categories(id) ON DELETE RESTRICT,
    price               NUMERIC(14, 2) NOT NULL CHECK (price >= 0),
    unit                VARCHAR(20) NOT NULL DEFAULT 'kg',
    is_available        BOOLEAN NOT NULL DEFAULT TRUE,
    valid_from          DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_until         DATE,
    source_note         TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_price_validity CHECK (valid_until IS NULL OR valid_until >= valid_from),
    CONSTRAINT uq_bank_subcategory_price UNIQUE (waste_bank_id, sub_category_id, valid_from)
);

CREATE TABLE analysis_records (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    analysis_type       VARCHAR(10) NOT NULL CHECK (analysis_type IN ('waste', 'plant')),
    status              VARCHAR(15) NOT NULL DEFAULT 'completed'
                        CHECK (status IN ('processing', 'completed', 'failed')),
    image_url           TEXT,
    image_storage_key   TEXT,
    ai_provider         VARCHAR(40) NOT NULL DEFAULT 'Google Gemini',
    ai_model            VARCHAR(80) NOT NULL DEFAULT 'Gemini 3.6 Flash',
    prompt_version      VARCHAR(40),
    result              JSONB,
    error_message       TEXT,
    analyzed_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_analysis_result_state CHECK (
        (status = 'completed' AND result IS NOT NULL AND error_message IS NULL)
        OR status IN ('processing', 'failed')
    )
);

-- Optional normalized classification for waste analysis.
-- The complete AI response remains in analysis_records.result for traceability.
CREATE TABLE analysis_waste_details (
    analysis_id         UUID PRIMARY KEY REFERENCES analysis_records(id) ON DELETE CASCADE,
    sub_category_id    BIGINT REFERENCES waste_sub_categories(id) ON DELETE SET NULL,
    is_recyclable       BOOLEAN,
    detected_name       VARCHAR(180),
    classification      VARCHAR(150),
    environmental_impact TEXT,
    recycling_tips      TEXT
);

-- Optional normalized summary for plant analysis.
-- Detailed symptoms, causes, care recommendations and prevention tips remain in JSONB.
CREATE TABLE analysis_plant_details (
    analysis_id          UUID PRIMARY KEY REFERENCES analysis_records(id) ON DELETE CASCADE,
    plant_name           VARCHAR(180),
    detected_pest_disease VARCHAR(180),
    symptoms             TEXT,
    possible_cause       TEXT,
    care_recommendation  TEXT,
    prevention_tips      TEXT,
    plant_impact         TEXT
);

CREATE INDEX idx_analysis_user_date
    ON analysis_records (user_id, analyzed_at DESC);
CREATE INDEX idx_analysis_type_date
    ON analysis_records (analysis_type, analyzed_at DESC);
CREATE INDEX idx_analysis_result_gin
    ON analysis_records USING GIN (result);
CREATE INDEX idx_waste_banks_active
    ON waste_banks (is_active);
CREATE INDEX idx_waste_bank_prices_lookup
    ON waste_bank_prices (sub_category_id, is_available, valid_from DESC);
CREATE INDEX idx_waste_sub_categories_category
    ON waste_sub_categories (category_id);

-- Relationship overview:
-- users 1 ── N analysis_records
-- analysis_records 1 ── 0..1 analysis_waste_details
-- analysis_records 1 ── 0..1 analysis_plant_details
-- waste_categories 1 ── N waste_sub_categories
-- waste_banks 1 ── N waste_bank_prices
-- waste_sub_categories 1 ── N waste_bank_prices
